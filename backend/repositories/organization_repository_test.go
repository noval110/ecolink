package repositories_test

import (
	"context"
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"os"
	"reflect"
	"strings"
	"testing"
	"time"

	"github.com/golang-jwt/jwt/v5"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/labstack/echo/v4"

	"github.com/noval110/ecolink/backend/handlers"
	"github.com/noval110/ecolink/backend/repositories"
	"github.com/noval110/ecolink/backend/routes"
)

func TestOrganizationRepositoryIntegration(t *testing.T) {
	dsn := os.Getenv("ECOLINK_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set ECOLINK_TEST_DATABASE_URL to run PostgreSQL integration checks with temporary tables")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	poolConfig, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal("invalid test database configuration")
	}
	poolConfig.MaxConns = 1
	poolConfig.MinConns = 0
	poolConfig.ConnConfig.RuntimeParams["search_path"] = "pg_temp"
	pool, err := pgxpool.NewWithConfig(ctx, poolConfig)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()

	// Only session-local tables are created; application tables are never changed.
	_, err = pool.Exec(ctx, `
		CREATE TEMP TABLE organizations (
			id bigint PRIMARY KEY, name text, type text, description text, location text, created_at timestamptz DEFAULT now()
		);
		CREATE TEMP TABLE organization_members (
			id bigint PRIMARY KEY, organization_id bigint, user_id bigint, role text, joined_at timestamptz
		);
		CREATE TEMP TABLE campaigns (
			id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
			organization_id bigint REFERENCES organizations(id), title text, description text,
			start_date date, end_date date, target_kg numeric(12,2), status text, created_at timestamptz DEFAULT now()
		);
		CREATE TEMP TABLE transactions (id bigint, campaign_id bigint, total_weight numeric, status text);
		CREATE TEMP TABLE campaigners (campaign_id bigint, user_id bigint, status text);
		CREATE TEMP TABLE waste_banks (id bigint PRIMARY KEY, name text);
		CREATE TEMP TABLE campaign_waste_banks (
			campaign_id bigint REFERENCES campaigns(id), waste_bank_id bigint REFERENCES waste_banks(id)
		);

		INSERT INTO organizations (id, name, type) VALUES (1, 'First Organization', 'university'), (2, 'Other Organization', NULL), (3, 'Empty Organization', NULL);
		INSERT INTO organization_members VALUES
			(1, 1, 10, 'admin', '2026-01-01'), (2, 2, 10, 'member', '2026-02-01'),
			(3, 2, 20, 'admin', '2026-01-01'), (4, 3, 30, NULL, '2026-01-01');
		INSERT INTO campaigns VALUES
			(1, 1, 'Active Campaign', 'Description', '2026-01-01', '2026-12-31', 1000, 'active', '2026-03-01'),
			(2, 1, 'Completed Campaign', NULL, NULL, NULL, 0, 'completed', '2026-02-01'),
			(3, 1, 'Empty Campaign', NULL, NULL, NULL, NULL, NULL, '2026-04-01'),
			(4, 2, 'Other Campaign', NULL, NULL, NULL, 100, 'active', '2026-05-01');
		INSERT INTO transactions VALUES
			(1, 1, 2.75, 'verified'), (2, 1, 2.75, 'verified'), (3, 1, 100, 'pending'),
			(4, 2, 3, 'verified'), (5, 4, 99, 'verified');
		INSERT INTO campaigners VALUES
			(1, 101, 'joined'), (1, 102, 'joined'), (1, 101, 'joined'), (1, 999, 'left'),
			(2, 101, 'joined'), (2, 103, 'joined'), (4, 201, 'joined');
		INSERT INTO waste_banks VALUES (1, 'Alpha Bank'), (2, 'Zeta Bank'), (3, 'Other Bank');
		INSERT INTO campaign_waste_banks VALUES (1, 2), (1, 1), (1, 1), (2, 1), (4, 3);
	`)
	if err != nil {
		t.Fatal(err)
	}

	repository := repositories.NewOrganizationRepository(pool)
	dashboard, err := repository.GetDashboard(ctx, 10)
	if err != nil {
		t.Fatal(err)
	}
	if dashboard.Organization.ID != 1 || dashboard.Organization.MemberRole == nil || *dashboard.Organization.MemberRole != "admin" {
		t.Fatalf("expected earliest organization membership, got %+v", dashboard.Organization)
	}
	if dashboard.CampaignCount != 3 || dashboard.ActiveCampaigns != 1 || dashboard.TotalParticipants != 3 || dashboard.TotalWasteCollected != 8.5 {
		t.Fatalf("unexpected dashboard totals: %+v", dashboard)
	}
	expectedPartners := []repositories.OrganizationPartnerBank{{ID: 1, Name: "Alpha Bank"}, {ID: 2, Name: "Zeta Bank"}}
	if !reflect.DeepEqual(dashboard.PartnerWasteBanks, expectedPartners) {
		t.Fatalf("expected distinct partners in name order, got %+v", dashboard.PartnerWasteBanks)
	}
	if got := []int64{dashboard.Campaigns[0].ID, dashboard.Campaigns[1].ID, dashboard.Campaigns[2].ID}; !reflect.DeepEqual(got, []int64{3, 1, 2}) {
		t.Fatalf("campaign order: %v", got)
	}
	active := dashboard.Campaigns[1]
	if active.CurrentWeight != 5.5 || active.Participants != 2 || active.ProgressPercentage != 0.55 {
		t.Fatalf("transactions must not multiply by participant rows: %+v", active)
	}
	if !reflect.DeepEqual(active.PartnerWasteBanks, expectedPartners) || active.StartDate == nil || active.StartDate.Format("2006-01-02") != "2026-01-01" {
		t.Fatalf("unexpected campaign partners or date: %+v", active)
	}
	emptyCampaign := dashboard.Campaigns[0]
	if emptyCampaign.TargetWeight != 0 || emptyCampaign.CurrentWeight != 0 || emptyCampaign.ProgressPercentage != 0 || emptyCampaign.Status != "" || emptyCampaign.PartnerWasteBanks == nil {
		t.Fatalf("empty campaign defaults: %+v", emptyCampaign)
	}
	if dashboard.Campaigns[2].ProgressPercentage != 0 {
		t.Fatal("zero targets must not divide by zero")
	}
	other, err := repository.GetDashboard(ctx, 20)
	if err != nil || other.Organization.ID != 2 || other.TotalWasteCollected != 99 {
		t.Fatalf("other membership scope: %+v, %v", other, err)
	}
	empty, err := repository.GetDashboard(ctx, 30)
	if err != nil || empty.CampaignCount != 0 || empty.TotalParticipants != 0 || empty.Campaigns == nil || empty.PartnerWasteBanks == nil {
		t.Fatalf("empty organization: %+v, %v", empty, err)
	}
	missing, err := repository.GetDashboard(ctx, 99)
	if err != nil || missing != nil {
		t.Fatalf("missing membership: %+v, %v", missing, err)
	}

	e := echo.New()
	handler := handlers.NewOrganizationDBHandler(repository)
	routes.RegisterRoutesWithAuth(e, handlers.NewAuthHandler(nil), nil, nil, nil, nil, nil, nil, nil, nil, handler, nil, "integration-secret")
	for _, endpoint := range []string{"/api/organization/dashboard", "/api/organization/campaigns"} {
		for _, userID := range []int64{10, 99} {
			token, err := jwt.NewWithClaims(jwt.SigningMethodHS256, jwt.MapClaims{
				"user_id": userID, "role": "organization", "exp": time.Now().Add(time.Hour).Unix(),
			}).SignedString([]byte("integration-secret"))
			if err != nil {
				t.Fatal(err)
			}
			request := httptest.NewRequest(http.MethodGet, endpoint+"?user_id=20&organization_id=2", nil).WithContext(ctx)
			request.Header.Set(echo.HeaderAuthorization, "Bearer "+token)
			response := httptest.NewRecorder()
			e.ServeHTTP(response, request)
			if userID == 99 {
				if response.Code != http.StatusNotFound {
					t.Fatalf("expected 404 for missing membership: %s", response.Body.String())
				}
				continue
			}
			if response.Code != http.StatusOK {
				t.Fatalf("expected 200: %s", response.Body.String())
			}
			var payload struct {
				Data json.RawMessage `json:"data"`
			}
			if err := json.Unmarshal(response.Body.Bytes(), &payload); err != nil {
				t.Fatal(err)
			}
			if endpoint == "/api/organization/dashboard" {
				var got repositories.OrganizationDashboard
				if err := json.Unmarshal(payload.Data, &got); err != nil || got.Organization.ID != 1 || got.TotalWasteCollected != 8.5 {
					t.Fatalf("JWT membership must control dashboard: %s", response.Body.String())
				}
			} else {
				var got []repositories.OrganizationCampaign
				if err := json.Unmarshal(payload.Data, &got); err != nil || len(got) != 3 || got[1].CurrentWeight != 5.5 || got[1].ProgressPercentage != 0.55 {
					t.Fatalf("JWT membership must control campaigns: %s", response.Body.String())
				}
			}
		}
	}

	postCampaign := func(userID int64, body string) *httptest.ResponseRecorder {
		t.Helper()
		token, err := jwt.NewWithClaims(jwt.SigningMethodHS256, jwt.MapClaims{
			"user_id": userID, "role": "organization", "exp": time.Now().Add(time.Hour).Unix(),
		}).SignedString([]byte("integration-secret"))
		if err != nil {
			t.Fatal(err)
		}
		request := httptest.NewRequest(http.MethodPost, "/api/organization/campaigns?organization_id=2&user_id=20", strings.NewReader(body)).WithContext(ctx)
		request.Header.Set(echo.HeaderContentType, echo.MIMEApplicationJSON)
		request.Header.Set(echo.HeaderAuthorization, "Bearer "+token)
		response := httptest.NewRecorder()
		e.ServeHTTP(response, request)
		return response
	}
	counts := func() [2]int {
		t.Helper()
		var result [2]int
		if err := pool.QueryRow(ctx, `SELECT (SELECT count(*) FROM campaigns), (SELECT count(*) FROM campaign_waste_banks)`).Scan(&result[0], &result[1]); err != nil {
			t.Fatal(err)
		}
		return result
	}

	validBody := `{"title":"  New Campaign  ","description":"Real campaign","start_date":"2026-10-25","end_date":"2026-11-25","target_kg":125.5,"partner_waste_bank_ids":[2,1,1],"organization_id":2,"user_id":20}`
	t.Run("missing membership cannot create", func(t *testing.T) {
		before := counts()
		response := postCampaign(99, validBody)
		if response.Code != http.StatusNotFound || counts() != before {
			t.Fatalf("expected 404 without writes: %d %s", response.Code, response.Body.String())
		}
	})
	t.Run("invalid partner rolls back campaign and earlier partners", func(t *testing.T) {
		before := counts()
		response := postCampaign(10, strings.Replace(validBody, "[2,1,1]", "[1,999]", 1))
		if response.Code != http.StatusBadRequest || !strings.Contains(response.Body.String(), "waste bank 999 not found") || counts() != before {
			t.Fatalf("expected 400 and complete rollback: %d %s", response.Code, response.Body.String())
		}
	})
	t.Run("creates active campaign scoped to JWT membership", func(t *testing.T) {
		before := counts()
		response := postCampaign(10, validBody)
		if response.Code != http.StatusCreated {
			t.Fatalf("expected 201: %d %s", response.Code, response.Body.String())
		}
		var payload struct {
			Message string                            `json:"message"`
			Data    repositories.OrganizationCampaign `json:"data"`
		}
		if err := json.Unmarshal(response.Body.Bytes(), &payload); err != nil {
			t.Fatal(err)
		}
		campaign := payload.Data
		if payload.Message != "Campaign created" || campaign.ID < 100 || campaign.Title != "New Campaign" || campaign.Description == nil || *campaign.Description != "Real campaign" || campaign.TargetWeight != 125.5 || campaign.Status != "active" || campaign.CurrentWeight != 0 || campaign.Participants != 0 || campaign.ProgressPercentage != 0 {
			t.Fatalf("unexpected created campaign: %s", response.Body.String())
		}
		if campaign.StartDate == nil || campaign.StartDate.Format("2006-01-02") != "2026-10-25" || campaign.EndDate == nil || campaign.EndDate.Format("2006-01-02") != "2026-11-25" || !reflect.DeepEqual(campaign.PartnerWasteBanks, expectedPartners) {
			t.Fatalf("unexpected dates or distinct partners: %+v", campaign)
		}
		var organizationID int64
		if err := pool.QueryRow(ctx, `SELECT organization_id FROM campaigns WHERE id = $1`, campaign.ID).Scan(&organizationID); err != nil || organizationID != 1 {
			t.Fatalf("body/query must not override JWT membership: %d, %v", organizationID, err)
		}
		after := counts()
		if after != [2]int{before[0] + 1, before[1] + 2} {
			t.Fatalf("duplicate partners must not create extra rows: before %v, after %v", before, after)
		}
		dashboard, err := repository.GetDashboard(ctx, 10)
		if err != nil || dashboard == nil || dashboard.CampaignCount != 4 || dashboard.ActiveCampaigns != 2 {
			t.Fatalf("new campaign must appear in dashboard: %+v, %v", dashboard, err)
		}
		other, err := repository.ListCampaigns(ctx, 2)
		if err != nil || len(other) != 1 || other[0].ID != 4 {
			t.Fatalf("other organization must remain unchanged: %+v, %v", other, err)
		}
	})
	t.Run("same day campaign and nullable description", func(t *testing.T) {
		body := `{"title":"One day","start_date":"2026-10-25","end_date":"2026-10-25","target_kg":1,"partner_waste_bank_ids":[1]}`
		response := postCampaign(10, body)
		var payload struct {
			Data repositories.OrganizationCampaign `json:"data"`
		}
		if err := json.Unmarshal(response.Body.Bytes(), &payload); err != nil || response.Code != http.StatusCreated || payload.Data.Description != nil || payload.Data.StartDate == nil || payload.Data.EndDate == nil || !payload.Data.StartDate.Equal(*payload.Data.EndDate) {
			t.Fatalf("expected same-day creation with null description: %d %s", response.Code, response.Body.String())
		}
	})

	patchStatus := func(userID int64, campaignID, body string) *httptest.ResponseRecorder {
		t.Helper()
		token, err := jwt.NewWithClaims(jwt.SigningMethodHS256, jwt.MapClaims{
			"user_id": userID, "role": "organization", "exp": time.Now().Add(time.Hour).Unix(),
		}).SignedString([]byte("integration-secret"))
		if err != nil {
			t.Fatal(err)
		}
		request := httptest.NewRequest(http.MethodPatch, "/api/organization/campaigns/"+campaignID+"/status?organization_id=2&user_id=20", strings.NewReader(body)).WithContext(ctx)
		request.Header.Set(echo.HeaderContentType, echo.MIMEApplicationJSON)
		request.Header.Set(echo.HeaderAuthorization, "Bearer "+token)
		response := httptest.NewRecorder()
		e.ServeHTTP(response, request)
		return response
	}
	t.Run("status changes require campaign ownership", func(t *testing.T) {
		for _, test := range []struct {
			name       string
			userID     int64
			campaignID string
			status     int
			message    string
		}{
			{"missing membership", 99, "1", http.StatusNotFound, "Organization not found for this user"},
			{"other organization campaign", 10, "4", http.StatusBadRequest, "campaign not found"},
			{"other organization member", 20, "1", http.StatusBadRequest, "campaign not found"},
			{"unknown campaign", 10, "99999", http.StatusBadRequest, "campaign not found"},
		} {
			t.Run(test.name, func(t *testing.T) {
				response := patchStatus(test.userID, test.campaignID, `{"status":"cancelled","organization_id":2,"user_id":20}`)
				if response.Code != test.status || !strings.Contains(response.Body.String(), test.message) {
					t.Fatalf("expected %d %q: %d %s", test.status, test.message, response.Code, response.Body.String())
				}
			})
		}
		var activeCount int
		if err := pool.QueryRow(ctx, `SELECT count(*) FROM campaigns WHERE id IN (1,4) AND status = 'active'`).Scan(&activeCount); err != nil || activeCount != 2 {
			t.Fatalf("rejected updates must not alter either organization's campaigns: %d, %v", activeCount, err)
		}
	})
	t.Run("status cycle persists and updates dashboard totals", func(t *testing.T) {
		for _, status := range []string{"completed", "cancelled", "active", "active"} {
			response := patchStatus(10, "1", `{"status":"`+status+`","organization_id":2}`)
			var payload struct {
				Message string `json:"message"`
				Data    struct {
					CampaignID int64  `json:"campaign_id"`
					Status     string `json:"status"`
				} `json:"data"`
			}
			if err := json.Unmarshal(response.Body.Bytes(), &payload); err != nil || response.Code != http.StatusOK || payload.Message != "Campaign status updated" || payload.Data.CampaignID != 1 || payload.Data.Status != status {
				t.Fatalf("expected successful %s update: %d %s", status, response.Code, response.Body.String())
			}
			var storedStatus, title string
			var target float64
			if err := pool.QueryRow(ctx, `SELECT status, title, target_kg::float8 FROM campaigns WHERE id = 1`).Scan(&storedStatus, &title, &target); err != nil || storedStatus != status || title != "Active Campaign" || target != 1000 {
				t.Fatalf("update must only persist status: %s %s %f, %v", storedStatus, title, target, err)
			}
			got, err := repository.GetDashboard(ctx, 10)
			activeCount := 2
			if status == "active" {
				activeCount++
			}
			if err != nil || got == nil || got.CampaignCount != 5 || got.ActiveCampaigns != activeCount || got.TotalWasteCollected != 8.5 || got.TotalParticipants != 3 {
				t.Fatalf("dashboard totals after %s: %+v, %v", status, got, err)
			}
		}
	})
}
